#!/usr/bin/env node
// Encrypts projects.private.json (gitignored) into src/data/projects.encrypted.ts
// so project URLs never appear in the committed source / shipped bundle in plaintext.
//
// Usage:  npm run encrypt:projects -- "your-password"

import { webcrypto as crypto } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const INPUT = resolve(process.cwd(), "projects.private.json");
const OUTPUT = resolve(process.cwd(), "src/data/projects.encrypted.ts");

const password = process.argv[2];
if (!password) {
  console.error("Usage: npm run encrypt:projects -- <password>");
  process.exit(1);
}
if (!existsSync(INPUT)) {
  console.error(`Missing ${INPUT}. Create a JSON array of project entries first.`);
  process.exit(1);
}

const plaintext = readFileSync(INPUT, "utf-8");
try {
  JSON.parse(plaintext);
} catch (e) {
  console.error("projects.private.json is not valid JSON:", e.message);
  process.exit(1);
}

const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));

const baseKey = await crypto.subtle.importKey(
  "raw",
  enc.encode(password),
  "PBKDF2",
  false,
  ["deriveKey"],
);
const key = await crypto.subtle.deriveKey(
  { name: "PBKDF2", salt, iterations: 200000, hash: "SHA-256" },
  baseKey,
  { name: "AES-GCM", length: 256 },
  false,
  ["encrypt"],
);
const ciphertext = await crypto.subtle.encrypt(
  { name: "AES-GCM", iv },
  key,
  enc.encode(plaintext),
);

const b64 = (b) => Buffer.from(b).toString("base64");
const blob = {
  salt: b64(salt),
  iv: b64(iv),
  ciphertext: b64(ciphertext),
};

const fileContents = `// Auto-generated by scripts/encrypt-projects.mjs — do not edit by hand.
// Re-run \`npm run encrypt:projects -- <password>\` after updating projects.private.json.
export const encryptedProjects = ${JSON.stringify(blob, null, 2)} as const;
`;

writeFileSync(OUTPUT, fileContents);
console.log(`✓ Encrypted ${plaintext.length} bytes → ${OUTPUT}`);
